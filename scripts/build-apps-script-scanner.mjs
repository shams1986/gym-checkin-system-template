import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const read = (file) => fs.readFileSync(path.join(root, file), "utf8").replace(/\r\n/g, "\n");
const outputs = new Map();

const sourceHtml = read("scanner/index.html");
const scannerHtml = sourceHtml
  .replace(/^\s*<link rel="manifest"[^>]*>\n/m, "")
  .replace(/^\s*<link rel="icon"[^>]*>\n/m, "")
  .replace(/^\s*<link rel="stylesheet"[^>]*>\n/m, '    <style><?!= includeScannerFile_("Scanner.css"); ?></style>\n')
  .replace(/^\s*<script src="\.\/config\.js"><\/script>\n/m, "")
  .replace(/^\s*<script type="module" src="\.\/app\.js"><\/script>\n/m, "")
  .replace("./assets/logo.svg", "")
  .replace("  </body>", '    <script>window.GYM_PUBLIC_CONFIG = <?!= scannerConfigJson ?>;</script>\n    <script><?!= includeScannerScript_("Scanner.js"); ?></script>\n  </body>');
outputs.set("apps-script/Scanner.html", "<!-- Generated by scripts/build-apps-script-scanner.mjs. -->\n" + scannerHtml);
outputs.set("apps-script/Scanner.css.html", "/* Generated from scanner/styles.css. */\n" + read("scanner/styles.css"));

const core = read("scanner/core.mjs").replace(/^export /gm, "");
const app = read("scanner/app.js")
  .replace(/^import \{[\s\S]*?\} from "\.\/core\.mjs";\n\n/, "")
  .replace(/^\s*registerServiceWorker\(\);\n/m, "");
outputs.set("apps-script/Scanner.js.html", "// Generated from scanner/core.mjs and scanner/app.js.\n" + core + "\n" + app);

const checkOnly = process.argv.includes("--check");
let stale = false;
for (const [file, content] of outputs) {
  const target = path.join(root, file);
  if (checkOnly) {
    if (!fs.existsSync(target) || read(file) !== content) {
      console.error(`${file} is stale; run node scripts/build-apps-script-scanner.mjs`);
      stale = true;
    }
  } else {
    fs.writeFileSync(target, content, "utf8");
    console.log(`Generated ${file}`);
  }
}
if (stale) process.exitCode = 1;
